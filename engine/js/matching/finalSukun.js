/**
 * تسكين الأواخر — ترجيحٌ عند التساوي التامّ، لا كلفة.
 *
 * النصّ غير المشكول يوافق بحورًا كثيرة موافقةً تامّة، فتتساوى درجاتها
 * ولا يبقى ما يرجّح إلا ترتيبُ القائمة — وهو ترجيحٌ لا يدلّ على شيء.
 *
 * وثمّ ما يدلّ: النبطي يُسكّن أواخر الكلمات ولا إعراب فيه. فإذا استوت
 * قراءتان واحتاجت إحداهما إلى حركةٍ مفترضة على آخر كلمة ولم تحتج
 * الأخرى، فالثانية أولى:
 *
 *     بسّ الدهر جحّاد   →   دَ‑هَرْ‑جِحْ   أولى من   دَهْ‑رِ‑جِحْ
 *
 * وهو **ترجيح لا منع**: لا يمسّ درجةً ولا يُسقط قراءة. والحركة
 * المضطرّ إليها لا تُعدّ عيبًا فيها، لأن القراءة التي تتجنّبها تدفع
 * ثمنها في مكان آخر فتنزل بالدرجة لا بالترجيح.
 *
 * مسنَده تقطيعٌ مرجعيّ واحد، وهو مسجَّل NEEDS_VALIDATION في
 * `lexicon.nabatiDialect`، ومفتاحه في البيانات `ranking.preferFinalSukun`.
 */

/**
 * كم حركةً مفترضة وقعت على آخر كلمة في هذه القراءة؟
 *
 * الشرط أربعة: المقطع مفتوح (لا قفل له)، وفاتحتُه آخرُ حرف في كلمتها،
 * وحركتُها مفترضة لا مكتوبة، وليست آخر الشطر — فآخر الشطر له الإشباع
 * وأحكام الوقف، لا الإعراب.
 *
 * @param {object[]} feet التفعيلات المختارة، لكل واحدة `ops`
 * @param {object[]} units الوحدات الصوتية
 * @returns {number}
 */
export function assumedFinalVowels(feet, units) {
  if (!units || !units.length || !feet || !feet.length) return 0;
  const last = units.length - 1;
  let n = 0;
  for (const foot of feet) {
    for (const op of foot.ops || []) {
      const e = op.edge;
      if (!e || e.meta.coda) continue;
      if (!e.meta.assumed) continue;
      const i = e.meta.onsetIndex;
      const u = units[i];
      if (!u || !u.wordFinal || i === last) continue;
      n += 1;
    }
  }
  return n;
}
